"""End-to-end demo on the committed sample data, writing evidence to sample_output/.

  python scripts/demo.py

Steps: fresh warehouse -> load sample -> verify against expected labels -> rerun (no-op)
-> forced rerun (no duplicates) -> late batch + injected failure -> retry -> sample queries.
"""
from __future__ import annotations

import contextlib
import io
import os
import shutil
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sessionize.cli import main as cli  # noqa: E402
from sessionize.timeutil import format_utc, from_epoch_ms  # noqa: E402

SAMPLE = ROOT / "data" / "sample"
OUT = ROOT / "sample_output"
DB = OUT / "warehouse.db"
REF = "2026-12-31T00:00:00Z"   # fixed 'now' so the demo is reproducible


def step(title: str, argv: list[str], log: list[str]) -> int:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = cli(argv)
    log += [f"## {title}", "", f"`python -m sessionize {' '.join(argv)}`  ->  exit code **{code}**", "",
            "```", buf.getvalue().strip(), "```", ""]
    print(f"[{code}] {title}")
    return code


def counts() -> str:
    c = sqlite3.connect(DB)
    try:
        return ", ".join(f"{t}={c.execute(f'SELECT COUNT(*) FROM {t}').fetchone()[0]}"
                         for t in ("events", "sessions", "session_events", "rejected_events"))
    finally:
        c.close()


def main() -> int:
    for p in (DB, DB.with_suffix(".db-wal"), DB.with_suffix(".db-shm")):
        p.unlink(missing_ok=True)
    for d in ("logs", "run_reports"):
        shutil.rmtree(OUT / d, ignore_errors=True)
    OUT.mkdir(exist_ok=True)

    base = ["run", "--input", "data/sample/input/events", "--users", "data/sample/input/users.csv",
            "--db", "sample_output/warehouse.db", "--out", "sample_output", "--reference-time", REF]
    log = ["# Demo transcript", "", "Generated by `python scripts/demo.py` from the committed sample data.", ""]

    step("1. First load of the sample batches", base, log)
    log += [f"Warehouse after step 1: {counts()}", ""]
    step("2. Validate against the generator's expected answers",
         ["verify", "--db", "sample_output/warehouse.db", "--expected", "data/sample/expected",
          "--report", "sample_output/validation_report.md"], log)
    step("3. Rerun the same input (files are skipped by content hash)", base, log)
    step("4. Forced reprocessing of the same input (no duplicates created)", base + ["--force"], log)
    log += [f"Warehouse after step 4 (unchanged): {counts()}", ""]

    # late batch: two events that bridge / extend existing sessions, one bad row
    late = OUT / "demo_late_batch" / "events_batch_late.csv"
    late.parent.mkdir(exist_ok=True)
    c = sqlite3.connect(DB)
    a = c.execute("SELECT s1.user_id, s1.session_end_epoch_ms, s2.session_start_epoch_ms FROM sessions s1 "
                  "JOIN sessions s2 ON s2.user_id = s1.user_id AND s2.user_session_seq = s1.user_session_seq + 1 "
                  "WHERE s2.session_start_epoch_ms - s1.session_end_epoch_ms < 3600000 "
                  "ORDER BY s1.user_id LIMIT 1").fetchone()
    c.close()
    mid = format_utc(from_epoch_ms((a[1] + a[2]) // 2))
    late.write_text("event_id,user_id,event_type,event_ts,page_url,device\n"
                    f"late_000001,{a[0]},click,{mid},/late,mobile\n"
                    "late_000002,u_000999,click,2026-11-02T10:00:00Z,/late,mobile\n", encoding="utf-8")
    log += [f"Late file bridges the gap between two sessions of `{a[0]}` (event at {mid}) and "
            "has one row with an unknown user.", ""]
    late_args = base[:]
    late_args[2] = "sample_output/demo_late_batch"
    os.environ["SESSIONIZE_FAULT_INJECT"] = "after_insert_events:late"
    step("5. Late batch with an injected failure after the events insert (rolled back)", late_args, log)
    del os.environ["SESSIONIZE_FAULT_INJECT"]
    log += [f"Warehouse after failed step 5 (unchanged): {counts()}", ""]
    step("6. Retry: the failed file is picked up again and the two sessions merge", late_args, log)
    log += [f"Warehouse after step 6: {counts()}", ""]
    step("7. Final full publish of the sample batches + late batch (rerun = no-op)",
         base[:2] + ["data/sample/input/events", "sample_output/demo_late_batch"] + base[3:], log)
    step("8. Sample analytical and operational queries", ["report", "--db", "sample_output/warehouse.db"], log)

    (OUT / "demo_transcript.md").write_text("\n".join(log), encoding="utf-8")
    print("wrote sample_output/demo_transcript.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
